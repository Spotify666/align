# Writes src/lib/traced-batter.ts from a traced clip (public/art/<name>.json): the picture's
# size, the moments to stop on, and one frame (contact) as the still drawn before the rest loads.
#   python scripts/trace/still.py public/art/front-foot-defence.json src/lib/traced-batter.ts 0,12,18,32
import json, sys
src, out, moments = sys.argv[1], sys.argv[2], [int(v) for v in sys.argv[3].split(",")]
d = json.load(open(src))
contact = moments[-1]
ts = f'''// Generated by scripts/trace/still.py from {src}. Do not edit by hand.
// The landing page's batter, traced frame by frame from a real clip (scripts/trace/README.md).

export const TRACED = {{
  /** Where the frames are fetched from (the whole movement, as shapes to fill). */
  src: "/{src.split("public/")[-1]}",
  width: {d["size"][0]},
  height: {d["size"][1]},
  /** Frames a second of the recording. */
  fps: {d["fps"]},
  frames: {len(d["paths"])},
  /** Where the feet stand, in the picture's own units. */
  ground: {d["ground"]},
  /** The frames to stop on: stance, backlift, stride, contact. */
  moments: {json.dumps(moments)},
  /** The contact frame, drawn as the still. */
  still: "{d["paths"][contact]}",
  /** The line at contact: front foot, front knee, front shoulder, head. */
  stillLine: {json.dumps(d["lines"][contact])},
}} as const;
'''
open(out, "w").write(ts)
print("wrote", out, len(ts), "bytes")
