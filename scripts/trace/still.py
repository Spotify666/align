# Writes src/lib/traced-batter.ts from a traced clip (public/art/<name>.json): the picture's
# size, the frame each phase of the shot begins on (read off the tracing), the frames to stop on (one
# in each phase after the stance), and the contact stop's frame as the still drawn before the rest loads.
#   python scripts/trace/still.py public/art/front-foot-defence.json src/lib/traced-batter.ts 0,8,15,19,24,27 13,17,21,25,32 3
# Phases: stance, backlift, stride, downswing, contact, follow-through. The last number is which
# stop is contact.
import json, sys
src, out = sys.argv[1], sys.argv[2]
phases = [int(v) for v in sys.argv[3].split(",")]
moments = [int(v) for v in sys.argv[4].split(",")]
contact = moments[int(sys.argv[5])]
d = json.load(open(src))
ts = f'''// Generated by scripts/trace/still.py from {src}. Do not edit by hand.
// The landing page's batter, traced frame by frame from a real clip (scripts/trace/README.md).

export const TRACED = {{
  /** Where the frames are fetched from (the whole movement, as shapes to fill). */
  src: "/{src.split("public/")[-1]}",
  width: {d["size"][0]},
  height: {d["size"][1]},
  /** Frames a second of the recording. */
  fps: {d["fps"]},
  frames: {len(d["paths"])},
  /** Where the feet stand, in the picture's own units. */
  ground: {d["ground"]},
  /** The frame each phase begins on: stance, backlift, stride, downswing, contact, follow-through. */
  phases: {json.dumps(phases)},
  /** The frames to stop on: backlift, stride, downswing, contact, follow-through. */
  moments: {json.dumps(moments)},
  /** Which stop is contact (the still, and where the line lights up). */
  contact: {sys.argv[5]},
  /** The contact frame, drawn as the still. */
  still: "{d["paths"][contact]}",
  /** The line at contact: front foot, front knee, front shoulder, head. */
  stillLine: {json.dumps(d["lines"][contact])},
}} as const;
'''
open(out, "w").write(ts)
print("wrote", out, len(ts), "bytes")
