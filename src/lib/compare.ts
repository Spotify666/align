// What a shot can be compared with: the textbook model (filmed side-on and from the bowler's
// end), professionals (the sideways line), the player's own earlier shots, and shots other
// players chose to share. Built-in references are made by the same engine that reads the
// player's own clips, so a match compares like with like.

import { PRO_SIDEWAYS, type ShotSignature } from "@/engine/signature";
// Computed at build time (src/lib/textbook-refs.ts): the engine never runs for them on the phone.
import TEXTBOOK from "./textbook-refs.json";

/**
 * Where a reference comes from and what Aline may do with it. Every reference carries one and
 * shows it; there is no reference without it. Numbers only: no reference carries footage.
 */
export interface Provenance {
  rights: "yours" | "generated" | "shared" | "research_unconfirmed";
  /** In a line, shown under the reference. */
  label: string;
}

export const PROVENANCE = {
  yours: { rights: "yours", label: "Your own shot, kept on this device" },
  usual: { rights: "yours", label: "Made from your own shots, kept on this device" },
  generated: { rights: "generated", label: "Generated by Aline's test generator. Not a real player" },
  shared: { rights: "shared", label: "Shared by the player for comparison. Numbers only, never video" },
  research_unconfirmed: {
    rights: "research_unconfirmed",
    label: "Medians from a research dataset (KU CricShot). Numbers only, no footage or names. Its licence for use as a reference is not yet confirmed",
  },
} satisfies Record<string, Provenance>;

export interface Reference {
  id: string;
  name: string;
  note: string;
  kind: "model" | "pro" | "you" | "usual" | "player";
  signature: ShotSignature;
  provenance: Provenance;
  when?: string;
}

let cache: Reference[] | null = null;

/** The textbook model (both camera positions) and the professionals' sideways line. */
export function builtInReferences(): Reference[] {
  if (cache) return cache;
  const textbook = TEXTBOOK as Partial<Record<"side_on" | "front_on", ShotSignature>>;
  const out: Reference[] = [];
  for (const view of ["side_on", "front_on"] as const) {
    const sig = textbook[view];
    if (sig)
      out.push({
        id: `textbook_${view}`,
        name: "Textbook defence",
        note: view === "side_on" ? "The coaching model, filmed side-on" : "The coaching model, filmed from the bowler's end",
        kind: "model",
        signature: structuredClone(sig),
        provenance: PROVENANCE.generated,
      });
  }
  out.push({ id: "pros_sideways", name: "International batters", note: "The line of 323 professional defences, seen from either end of the pitch", kind: "pro", signature: PRO_SIDEWAYS, provenance: PROVENANCE.research_unconfirmed });
  cache = out;
  return out;
}

/** A likeness in words, for readers who get no numbers. */
export const likeness = (score: number) => (score >= 85 ? "close" : score >= 65 ? "some way off" : "far off");
